#pragma once

/*
 * ui_screen — 屏幕几何的唯一真相 (v6.9 → v7.3 实测重写)。
 *
 * ── v7.3：整个 LVGL 空间都是可见的 ───────────────────────────────
 * 这个文件原本的核心断言是"LVGL 有 480 宽、面板只点亮其中 466、起点 a
 * 未知"。**实测证明前提就是错的**：`?vis` 标尺（ui_calib.c）在两轴上
 * 分别探到 1/2/4/5 与 468/472/476/479，**全部可见**——可见区就是
 * [0, 479]×[0, 479]，没有偏移，也没有 14px 的屏外余量。
 *
 * 那个 466 是产品规格上的物理像素数，从来没有人在 LVGL 坐标里验证过它
 * 与坐标空间的关系（面板/控制器如何把 480 列映射到 466 个物理像素是它
 * 自己的事，对绘制不可见）。把规格数字当成坐标事实，代价是：
 *   · 贴边元素按 466 方框锚定 → 左/上缩 3px、右/下缩 17px，就是用户
 *     报的"右侧和底部有间隙"（不对称正是 480-466-3 = 11 的来源）；
 *   · 按 466 方框画的四个圆角弧全都明显缩在里面（用户："四个圆角都没
 *     贴边"）；
 *   · 历史上那套 a ∈ [1,6] 的"夹逼"是在错误模型里做的，一并作废。
 *
 * 结论：**贴边绘制直接用 [0, UI_LV_W-1]，不需要任何原点补偿。**
 *
 * 唯一还需要一双眼睛的量是圆角半径（`?vis 3`）——面板四角是圆的，贴边
 * 元素的圆角要与它同心才不会在拐角处切进切出。换面板批次要复量。
 *
 * 截图读不出这些：`?dump` 渲染的是整个 480×480 帧缓冲【缩放】到 466
 * （实测：LVGL 第 465 列出现在截图第 451 列 = 465×466/480），不是可见区
 * 裁剪——物理上哪一列点亮根本不在帧缓冲里。**改用 `--size 480` 截图**
 * 才是 1:1。
 *
 * ── 布局（v7.4 已修） ────────────────────────────────────────────
 * 各场景的 `SCREEN_W` 与 ui_type.h 的 `UI_CONTENT_W`（410 = 466-2*28）
 * 都是从同一个错误前提推出来的，于是凡是【靠计算居中】的东西都左偏
 * 7px。要分清哪些受影响：
 *   · 不受影响 —— 用 LV_ALIGN_*_MID / CENTER 的元素相对父容器居中，
 *     父容器本来就是 480：顶部时钟、ambient 簇、nav_dots 中间那点、
 *     status_bar 一直都是对的；
 *   · 受影响 —— 用 set_pos(0,0) + 466 宽容器的（weather 的 wx_grp /
 *     strip_grp），以及由 466 算出的宽度（ROW_X、UI_CONTENT_W）。
 * 实测（1:1 的 480 截图，排除边缘辉光带）：五日条带墨迹中心
 * 233.0 -> 240.0（真中心 239.5）；fleet 卡片边距 28/42 -> 28/28。
 *
 * 纵向【维持现状，这是个决定，不是遗漏】：内容全部顶部锚定，多出来的
 * 14px 全落在底部（footer caption 墨底距下边缘 18px，而设计当初按 466
 * 调的是 4px）。已在实机上看过，观感没问题——底部多一点留白反而比当年
 * 4px 的紧贴舒服。除非有人明确提出，不要去"修"它：那不是正确性缺陷，
 * 改动会牵动整套已调好的纵向节奏。
 */

#define UI_LV_W        480   /* LVGL 坐标空间 */

/* 可见区 == 坐标空间。v7.3 四边对称复核：每条边距边缘 0/3/7/12px 的
 * 刻度条【四边全部可见】，含最极端的第 0 与第 479 行/列。
 * 保留这个别名只为语义清晰（"贴边"用它，"布局"用 UI_LV_W）。 */
#define UI_VIS_W       UI_LV_W

/* 面板原点偏移的上界。实测夹逼：
 *   辉光摆在 7..472 时右/下被切  -> a + 465 < 472 -> a < 7
 *   辉光摆在 0..465 时左上缺一点 -> a > 0
 * 即 a ∈ [1,6]。
 *
 * v6.9: 从上界 6 调到 3（当时以为可见区只有 466、起点未知）。
 * v7.3 作废：可见区就是整个坐标空间，没有原点偏移，也就没有"安全余量"
 * 可留——这 3px 内缩正是右/下缺口的一半来源。保留为 0 仅为兼容尚未迁移
 * 的引用；**新代码不要用它**。 */
#define UI_VIS_INSET     0

/* 可见区原点 = 0（v7.3 实测；见文件头的测量链）。保留常量是为了让
 * "贴边"的意图在代码里显式可读，也方便将来换面板批次时只改这一处。 */
#define UI_VIS_ORG       0

/* 贴边元素的可用方框：(UI_VIS_INSET, UI_VIS_INSET) 起，边长 UI_VIS_BOX。 */
#define UI_VIS_BOX     (UI_VIS_W - 2 * UI_VIS_INSET)

/* 面板圆角。v7.3 用 `?vis 3` 四轮二分实测（一角一个候选半径并行比对）：
 *   60 被切 / 78 可见但有缝     -> (60, 78]
 *   64 全切 / 68 大部切 / 72 部分切 / 76 完整 -> (72, 76]
 *   73 两端切 / 74 顶端切 / 75 左侧切 / 76 完整 -> **76**
 * 判据：候选半径【小于】真值时，弧落在面板圆角切掉的区域里 -> 看不见；
 * 【大于】真值则整条可见但与边缘留缝。所以"最小的那条完整弧"即真值。
 * 旧值 60 偏小 16px——贴边元素的拐角因此总差一口气。
 * 贴边元素的圆角应与它一致（或按自身内缩量同步递减，保持同心）。 */
#define UI_VIS_RADIUS   76
