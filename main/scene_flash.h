#pragma once
#include "lvgl.h"

/*
 * scene_flash — "你已经在这个界面了" 的边框高光 (v6.6)。
 *
 * 三个按键各自直达一个界面（BOOT=总览 / USER=天气 / PWR=时间）。当按下
 * 的键指向的正是当前（或正在切往的）界面时，没有场景可切，于是用一圈
 * 边框高光回应：既确认"我收到了这次按键"，又说明"你已经在这里"。
 *
 * 为什么放在 lv_layer_top()：它跨场景，且必须画在所有场景内容之上；
 * 挂在某个场景根上就得复制三份，还会被场景切换连带隐藏。
 *
 * 渲染成本注意：这个环的包围盒就是整块屏，所以每次重绘都会连带重画它
 * 底下那一圈里的场景内容。因此动画走【低频步进】而不是逐帧 opa 动画
 * （CLAUDE.md 的渲染铁律），并且只持续几百毫秒。实测数字见 scene_flash.c。
 */

/* app_main 里创建一次（需要 LVGL 已初始化）。 */
void scene_flash_init(void);

/* 触发一次高光。重复触发会重新开始，不会叠加。 */
void scene_flash_ping(void);
